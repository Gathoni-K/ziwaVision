# ══════════════════════════════════════════════════════════════════════════════
# CASE 5 — Shape mismatch (SCL / lake mismatch causes assertion)
# ══════════════════════════════════════════════════════════════════════════════

dr5 = DemoResult("5. Shape mismatch", "Wrong-size lake_filled → OpenCV assertion")

import dataclasses

