"""
run_fault_demo.py — Reproducible fault-injection demonstration for ZiwaVision.

Covers six failure categories with controlled injection:
  1. Transient STAC/network failure (STAC query raises ConnectionError)
  2. Retry exhaustion (find_scenes returns [] after 2 attempts)
  3. Missing asset (read_band raises FileNotFoundError)
  4. Empty candidate mask (lake_mask returns all-zero array)
  5. Shape mismatch (SCL array has wrong shape)
  6. Maximum-step termination (max_steps=1 on a looping scene)

All failures are SIMULATED through controlled injection.
No real satellite service was harmed or misrepresented.
Labels: [SIMULATED FAILURE] marks every injected fault.

The demo prints the real trace records generated by the implementation
and summarises outcomes in a table.
"""

