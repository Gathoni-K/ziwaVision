# ── synthetic scene helper ────────────────────────────────────────────────────

def _make_ctx(add_veg: bool = True, h: int = 300, w: int = 300) -> SceneContext:
    lake = np.zeros((h, w), dtype=np.uint8)
    cv2.circle(lake, (150, 150), 120, 1, -1)
    np.random.seed(42)
    noise = np.random.normal(0, 10, (h, w)).astype(np.float32)
    red   = np.full((h, w), 1500.0, dtype=np.float32) + noise
    green = np.full((h, w), 1500.0, dtype=np.float32) + noise
    blue  = np.full((h, w), 1500.0, dtype=np.float32) + noise
    nir   = np.full((h, w), 1200.0, dtype=np.float32) + noise
    scl   = np.full((h, w), 5, dtype=np.uint8)
    red[lake == 1]   = 300.0  + noise[lake == 1]
    green[lake == 1] = 450.0  + noise[lake == 1]
    blue[lake == 1]  = 600.0  + noise[lake == 1]
    nir[lake == 1]   = 200.0  + noise[lake == 1]
    scl[lake == 1]   = 6
    if add_veg:
        veg = np.zeros((h, w), dtype=np.uint8)
        cv2.circle(veg, (150, 150), 8, 1, -1)
        red[veg == 1]   = 200.0  + noise[veg == 1]
        green[veg == 1] = 850.0  + noise[veg == 1]
        nir[veg == 1]   = 2800.0 + noise[veg == 1]
        scl[veg == 1]   = 4
    return SceneContext(
        scene_id="FAULT_DEMO_SCENE",
        date="2026-08-23",
        location="Dunga Beach, Winam Gulf",
        bbox=[34.73, -0.22, 34.83, -0.12],
        red=red, nir=nir, green=green, blue=blue, scl=scl,
        lake_filled=lake,
        reference_lake=lake.copy(),
        reference_mask=np.zeros((h, w), dtype=np.uint8),
    )


# ── result accumulator ────────────────────────────────────────────────────────

class DemoResult:
    def __init__(self, label: str, failure: str):
        self.label = label
        self.failure = failure
        self.attempts: str = "–"
        self.outcome: str = "–"
        self.trace_confirmed: bool = False
        self.traces: List[Dict[str, Any]] = []

    def show(self) -> None:
        print(f"\n{'─' * 68}")
        print(f"  {self.label}")
        print(f"{'─' * 68}")
        print(f"  Failure type : {self.failure}")
        print(f"  Attempts     : {self.attempts}")
        print(f"  Outcome      : {self.outcome}")
        print(f"  Trace valid  : {'YES ✓' if self.trace_confirmed else 'NO ✗'}")
        if self.traces:
            print(f"  Trace steps  :")
            for t in self.traces:
                step = t.get("step", "?")
                dec  = t.get("decision", "?")
                out  = (t.get("outcome") or "")[:72]
                print(f"    [{step}] {dec} → {out}")

    def row(self) -> str:
        ok = "✓" if self.trace_confirmed else "✗"
        return (
            f"| {self.label:<42} | {self.attempts:<18} | {self.outcome:<36} | {ok} |"
        )


results: List[DemoResult] = []


# ══════════════════════════════════════════════════════════════════════════════
# CASE 1 — Transient STAC/network failure
# ══════════════════════════════════════════════════════════════════════════════

dr1 = DemoResult("1. Transient STAC/network failure", "ConnectionError on find_scenes")

import inspector as _inspector_mod

_original_find_scenes = _inspector_mod.find_scenes

def _fail_find_scenes(bbox, date_range, max_items=5):
    raise ConnectionError("[SIMULATED FAILURE] STAC endpoint unreachable")

_inspector_mod.find_scenes = _fail_find_scenes
try:
    res = run_live_inspection("2026-08-23")
    dr1.traces = res.get("traces", [])
    dr1.outcome = f"ok={res['ok']}, status={res.get('status')}"
    dr1.attempts = "1 attempt (immediate failure)"
    # Retries produce intermediate 'stac_query_retry' records; the final
    # record (or any record) must be 'access_failure' to confirm the outcome.
    dr1.trace_confirmed = (
        len(dr1.traces) >= 1
        and any(t.get("decision") == "access_failure" for t in dr1.traces)
        and res["ok"] is False
    )
finally:
    _inspector_mod.find_scenes = _original_find_scenes

results.append(dr1)


# ══════════════════════════════════════════════════════════════════════════════
