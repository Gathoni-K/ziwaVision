ctx_bad = dataclasses.replace(
    ctx_mismatch,
    lake_filled=np.zeros((50, 50), dtype=np.uint8),
)

mismatch_raised = False
mismatch_msg = ""
try:
    with tempfile.TemporaryDirectory() as tmpdir:
        records = inspect_hotspot(ctx_bad, [], max_steps=4)
    # If it did not raise, it must have produced an explicit decision
    dr5.traces = [r.to_dict() for r in records]
    dr5.outcome = f"Completed: {records[-1].decision if records else 'no records'}"
    dr5.attempts = "1 attempt (shape mismatch handled)"
    dr5.trace_confirmed = len(records) > 0
except (AssertionError, ValueError, cv2.error) as exc:
    mismatch_raised = True
    mismatch_msg = str(exc)[:120]
    dr5.outcome = f"Exception raised (safe failure): {type(exc).__name__}"
    dr5.attempts = "1 attempt (exception)"
    dr5.trace_confirmed = True  # raising is the correct safe behaviour
    # Write a synthetic trace so the table shows a record
    with tempfile.TemporaryDirectory() as tmpdir:
        rec = TraceRecord(
            scene_id="FAULT_DEMO_SCENE",
            date="2026-08-23",
            location="Dunga Beach, Winam Gulf",
            step=0,
            observation={"error": mismatch_msg, "simulated": True},
            decision="shape_mismatch_exception",
            rule="[SIMULATED FAILURE] Wrong lake_filled shape passed to inspect_hotspot",
            outcome=f"{type(exc).__name__}: shape mismatch raised safely.",
        )
        dr5.traces = [rec.to_dict()]

results.append(dr5)


