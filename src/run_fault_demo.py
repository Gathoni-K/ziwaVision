def _fail_lake_mask(scl):
    return None  # simulates cloud-covered or invalid SCL

_original_box_cloud = _inspector_mod.box_cloud

def _zero_cloud(scl):
    return 0.0

_DummyScene2 = type("_DS2", (), {"id": "S2_FAULT_EMPTY_MASK"})()

